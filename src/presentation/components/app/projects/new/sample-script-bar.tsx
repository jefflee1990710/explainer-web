// One-click sample script pills for Step 02 so new users can test storyboard generation without writer's block.
export function SampleScriptBar({
  disabled,
  talkingHead,
  onApply,
}: {
  disabled?: boolean;
  talkingHead?: boolean;
  onApply: (script: string) => void;
}) {
  const { locale } = useI18n();

  const prefixLabel =
    locale === "zh-Hant"
      ? "沒有靈感？一鍵帶入範例劇本："
      : locale === "zh-Hans"
        ? "没有灵感？一键带入范例剧本："
        : "Need inspiration? Try a sample script:";

  return (
    <div className="mt-2.5 flex flex-wrap items-center gap-2">
      <span className="text-xs font-medium text-muted">{prefixLabel}</span>
      {SAMPLE_PRESETS.map((preset) => {
        const label =
          locale === "zh-Hant"
            ? preset.labelZhHant
            : locale === "zh-Hans"
              ? preset.labelZhHans
              : preset.labelEn;
        const text =
          locale === "zh-Hant"
            ? preset.sourceZhHant
            : locale === "zh-Hans"
              ? preset.sourceZhHans
              : preset.sourceEn;
        return (
          <button
            key={preset.id}
            type="button"
            disabled={disabled}
            onClick={() => onApply(text)}
            data-talking-head={talkingHead ? "true" : undefined}
            className="inline-flex cursor-pointer items-center rounded-full border border-accent-ink/15 bg-paper px-3 py-1 text-xs font-semibold text-foreground transition hover:border-accent-ink/35 hover:bg-accent-ink/5 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {label}
          </button>
        );
      })}
    </div>
  );
}
