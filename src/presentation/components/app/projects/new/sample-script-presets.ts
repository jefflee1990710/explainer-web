function pickLocale(locale: string, zhHant: string, zhHans: string, en: string) {
  if (locale === "zh-Hant") return zhHant;
  if (locale === "zh-Hans") return zhHans;
  return en;
}

// Talking-head samples fill two different fields. Other directors get one brief.
export function sampleApplyFor(
  preset: SamplePreset,
  locale: string,
  talkingHead: boolean,
): SampleApply {
  if (!talkingHead) {
    return {
      source: pickLocale(locale, preset.sourceZhHant, preset.sourceZhHans, preset.sourceEn),
    };
  }
  return {
    source: pickLocale(
      locale,
      preset.instructionZhHant,
      preset.instructionZhHans,
      preset.instructionEn,
    ),
    spokenScript: pickLocale(locale, preset.spokenZhHant, preset.spokenZhHans, preset.spokenEn),
  };
}
