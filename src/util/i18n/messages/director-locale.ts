const allPacks: Partial<Record<LocaleId, DirectorPack>> = { ...packs, ...more };

// Overlay director names, blurbs, and page chrome for locales that are not authored in full.
export function applyDirectorLocale(locale: LocaleId, messages: Messages): Messages {
  const pack = allPacks[locale];
  if (!pack) return messages;
  return {
    ...messages,
    nav: { ...messages.nav, directors: pack.nav, products: pack.products },
    directors: pack.directors,
    brief: {
      ...messages.brief,
      videoTypes: pack.videoTypes,
      videoTypeBlurbs: pack.blurbs,
    },
  };
}
